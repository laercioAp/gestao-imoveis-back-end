
CREATE TABLE contrato_clausulas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    contrato_id BIGINT NOT NULL,

    ordem INTEGER NOT NULL,

    titulo VARCHAR(200) NOT NULL,

    conteudo TEXT NOT NULL,

    ativa BOOLEAN NOT NULL DEFAULT TRUE,

    personalizada BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT fk_contrato_clausulas_contrato
        FOREIGN KEY (contrato_id)
        REFERENCES contratos(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_contrato_clausulas_ordem
        CHECK (ordem > 0)
);

CREATE INDEX idx_contrato_clausulas_contrato
    ON contrato_clausulas(contrato_id);

CREATE INDEX idx_contrato_clausulas_ordem
    ON contrato_clausulas(contrato_id, ordem);
