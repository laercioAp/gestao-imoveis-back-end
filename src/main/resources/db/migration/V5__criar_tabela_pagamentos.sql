
CREATE TABLE pagamentos (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                            contrato_id BIGINT NOT NULL,

                            competencia DATE NOT NULL,

                            valor_previsto NUMERIC(12, 2) NOT NULL,

                            valor_pago NUMERIC(12, 2),

                            data_vencimento DATE NOT NULL,

                            data_pagamento DATE,

                            forma_pagamento VARCHAR(30),

                            status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE',

                            observacoes TEXT,

                            criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                            CONSTRAINT fk_pagamentos_contrato
                                FOREIGN KEY (contrato_id)
                                    REFERENCES contratos(id)
                                    ON DELETE RESTRICT,

                            CONSTRAINT uk_pagamentos_contrato_competencia
                                UNIQUE (contrato_id, competencia),

                            CONSTRAINT ck_pagamentos_valor_previsto
                                CHECK (valor_previsto > 0),

                            CONSTRAINT ck_pagamentos_valor_pago
                                CHECK (valor_pago IS NULL OR valor_pago >= 0),

                            CONSTRAINT ck_pagamentos_status
                                CHECK (status IN ('PENDENTE', 'PAGO'))
);

CREATE INDEX idx_pagamentos_contrato
    ON pagamentos(contrato_id);

CREATE INDEX idx_pagamentos_status
    ON pagamentos(status);

CREATE INDEX idx_pagamentos_vencimento
    ON pagamentos(data_vencimento);

CREATE INDEX idx_pagamentos_competencia
    ON pagamentos(competencia);