
CREATE TABLE contratos (
                           id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

                           imovel_id BIGINT NOT NULL,
                           inquilino_id BIGINT NOT NULL,

                           finalidade VARCHAR(100) NOT NULL,
                           valor_aluguel NUMERIC(12, 2) NOT NULL,
                           dia_vencimento INTEGER NOT NULL,

                           data_inicio DATE NOT NULL,
                           data_fim DATE,

                           indice_reajuste VARCHAR(50),
                           valor_caucao NUMERIC(12, 2),

                           observacoes TEXT,

                           status VARCHAR(20) NOT NULL DEFAULT 'RASCUNHO',

                           criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
                           atualizado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

                           CONSTRAINT fk_contratos_imovel
                               FOREIGN KEY (imovel_id)
                                   REFERENCES imoveis(id)
                                   ON DELETE RESTRICT,

                           CONSTRAINT fk_contratos_inquilino
                               FOREIGN KEY (inquilino_id)
                                   REFERENCES inquilinos(id)
                                   ON DELETE RESTRICT,

                           CONSTRAINT ck_contratos_valor_aluguel
                               CHECK (valor_aluguel > 0),

                           CONSTRAINT ck_contratos_dia_vencimento
                               CHECK (dia_vencimento BETWEEN 1 AND 31),

                           CONSTRAINT ck_contratos_status
                               CHECK (status IN ('RASCUNHO', 'ATIVO', 'ENCERRADO'))
);

CREATE INDEX idx_contratos_imovel
    ON contratos(imovel_id);

CREATE INDEX idx_contratos_inquilino
    ON contratos(inquilino_id);

CREATE INDEX idx_contratos_status
    ON contratos(status);